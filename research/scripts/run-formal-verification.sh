#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

JAR="${TLA_TOOLS_JAR:-$ROOT/tools/tla2tools.jar}"
BASE_DIR="$ROOT/docs/formal"
MUT_DIR="$BASE_DIR/mutation-tests"
OUT_DIR="$BASE_DIR/results"
mkdir -p "$OUT_DIR"

if [[ ! -f "$JAR" ]]; then
  echo "TLC jar missing; running setup..."
  "$ROOT/scripts/setup-formal-tools.sh"
fi

run_one() {
  local name="$1" dir="$2" cfg="$3" tla="$4"
  local log="$OUT_DIR/${name}.log"
  echo "=== TLC: $name ==="
  set +e
  (cd "$dir" && java -XX:+UseParallelGC -Xmx1g -cp "$JAR" tlc2.TLC -config "$cfg" "$tla") 2>&1 | tee "$log"
  local rc=${PIPESTATUS[0]}
  set -e
  echo "TLC exit code: $rc"
  return "$rc"
}

base_rc=0
mutant_rc=0
run_one base "$BASE_DIR" GuardRuntime.cfg GuardRuntime.tla || base_rc=$?
run_one stale-approval-mutant "$MUT_DIR" GuardRuntime_StaleApproval_Mutant.cfg GuardRuntime_StaleApproval_Mutant.tla || mutant_rc=$?

# Base must finish cleanly. Mutant must fail specifically because the stale-approval
# invariant is violated; any other TLC failure is treated as infrastructure/model error.
if [[ "$base_rc" -ne 0 ]] || ! grep -q 'Model checking completed\. No error has been found\.' "$OUT_DIR/base.log"; then
  echo "FORMAL VERIFICATION FAILED: base model did not complete cleanly." >&2
  exit 10
fi

if ! grep -q 'Invariant StaleApprovalCannotReplay is violated' "$OUT_DIR/stale-approval-mutant.log"; then
  echo "FALSIFIABILITY CHECK FAILED: mutant did not produce the expected stale-approval counterexample." >&2
  exit 11
fi

cat > "$OUT_DIR/VERIFIED.md" <<DOC
# TLC verification results

Generated by scripts/run-formal-verification.sh.

- Base model: PASS — TLC completed with no error.
- Stale-approval mutant: PASS — TLC produced a counterexample for `StaleApprovalCannotReplay`.
- Raw logs: `base.log`, `stale-approval-mutant.log`.
- TLC tool: official v1.7.4, SHA-1 `bee4a54f3ee3d4afc347c3240ec2d9e93b075104`.

These results verify only the bounded finite TLA+ model represented by the supplied configs; they are not a proof of the TypeScript implementation as a whole.
DOC

echo "Formal verification complete."
